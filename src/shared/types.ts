/**
 * The single source of truth for the project + scene data format.
 *
 * Everything in `shared/` is imported by BOTH the editor and the runtime
 * loader that ships inside a real game, so nothing here may depend on React
 * or on any editor UI code.
 *
 * The format is deliberately plain JSON: scene files are what the editor
 * reads, what the exporter emits, and what the game loads. There is no
 * separate "import" step that could lose data.
 */

// ---------------------------------------------------------------------------
// Assets
// ---------------------------------------------------------------------------

/**
 * `tileset` is read from folders written when Mosaic painted tiles itself; it
 * loads as an image and nothing creates one any more.
 */
export type AssetKind = "image" | "spritesheet" | "tileset" | "atlas" | "audio" | "tilemap";

/**
 * What Mosaic knows about a Tiled map without holding the whole of it.
 *
 * Refreshed from the file every time the project is read, so it describes the
 * map as it is on disk rather than as it was when it was added.
 */
export interface TilemapInfo {
  tileWidth: number;
  tileHeight: number;
  cols: number;
  rows: number;
  /** Names of the map's tile layers, bottom first. */
  layers: string[];
  /** Each tileset, and the key of the project image it draws with. */
  tilesets: { name: string; image: string | null; imagePath: string }[];
  /** True when any tile carries the `collides` property. */
  collides: boolean;
  /** Why the map will not load cleanly in Phaser, when it will not. */
  issues?: string[];
}

export interface AssetFrame {
  name: string;
  x: number;
  y: number;
  w: number;
  h: number;
  /** Normalised 0..1 pivot. Placement and body defaults both read this. */
  pivotX: number;
  pivotY: number;
}

export interface AssetDef {
  id: string;
  /** Phaser loader key. Unique within the project. */
  key: string;
  kind: AssetKind;
  /** Virtual path inside the project, e.g. "assets/hero.png". */
  path: string;
  /** The copied bytes, as a data: URL. Assets are always copied in. */
  url: string;
  width: number;
  height: number;
  /** spritesheet + tileset */
  frameWidth?: number;
  frameHeight?: number;
  margin?: number;
  spacing?: number;
  /** atlas */
  frames?: AssetFrame[];
  /** tileset: indices flagged as colliding, authored once on the tileset. */
  tileCollides?: number[];
  /** Procedural placeholder generated by the editor rather than imported. */
  generated?: boolean;
  /** tilemap: a description of the Tiled map at `path`. */
  tilemap?: TilemapInfo;
}

// ---------------------------------------------------------------------------
// Layers — tile layers and object layers share one ordered list, because
// draw order must be one ordering and not two.
// ---------------------------------------------------------------------------

interface LayerBase {
  id: string;
  name: string;
  visible: boolean;
  locked: boolean;
}

/**
 * One tile layer of a Tiled map, placed in the scene's draw order.
 *
 * The tiles are not here. They are in the map file, edited in Tiled; this says
 * which map, which of its layers, and — by where it sits in `layers` — what it
 * draws above and below.
 */
export interface TileLayer extends LayerBase {
  kind: "tile";
  /** Key of the tilemap asset. */
  map: string;
  /** Name of the tile layer inside that map. */
  layer: string;
}

export interface ObjectLayer extends LayerBase {
  kind: "object";
}

export type Layer = TileLayer | ObjectLayer;

// ---------------------------------------------------------------------------
// Objects
// ---------------------------------------------------------------------------

export type BodyShape = "box" | "circle";

export interface BodyDef {
  shape: BodyShape;
  width: number;
  height: number;
  radius: number;
  offsetX: number;
  offsetY: number;
  immovable: boolean;
  allowGravity: boolean;
  bounce: number;
  /**
   * Kept inside the scene's bounds.
   *
   * Absent on bodies written before this was authorable, and read as `true`
   * there, which is the behaviour those scenes were built against.
   */
  collideWorldBounds?: boolean;
}

/**
 * A script component attached to an object.
 *
 * The class lives in the project's own source tree; the scene file stores only
 * the reference and the values authored in the editor. `src` is what makes the
 * reference resolvable when two classes share a name, and it is kept even when
 * the class cannot be found, so an unresolved script is never silently dropped.
 */
export interface ScriptRef {
  /** Exported class name, e.g. "PlayerController". */
  class: string;
  /** Project-relative source path, e.g. "src/scripts/PlayerController.ts". */
  src: string;
  /** Disabled scripts are still constructed; create/update are skipped. */
  enabled: boolean;
  /** Values for the class's @property fields. Undeclared keys are stale. */
  props: Record<string, unknown>;
}

/**
 * A text object's own settings.
 *
 * Text is CONTENT — a score readout, a label, a title — so it is authored here
 * rather than built in create(). Before this existed, every visible thing in a
 * Mosaic scene could be authored except the words on it.
 */
export interface TextDef {
  content: string;
  fontFamily: string;
  /** px */
  fontSize: number;
  color: string;
  align: "left" | "center" | "right";
  /** Wrap width in px; 0 leaves it unwrapped. */
  wrapWidth: number;
  stroke?: string;
  strokeThickness?: number;
  backgroundColor?: string;
  /**
   * Pinned to the camera rather than to the world — a HUD stays put while the
   * level scrolls under it.
   */
  fixed?: boolean;
}

/**
 * A sound an object plays for itself. Anything conditional — a sound on
 * contact, a sound only when falling — is behaviour, and belongs in code.
 */
export interface SoundRefs {
  /** Played once, when the object is created. */
  spawn?: string;
}

export interface SceneObject {
  id: string;
  name: string;
  /** A rendering hint: "sprite", "text" or "container". Nothing branches on it. */
  type: string;
  layerId: string;
  parentId: string | null;
  x: number;
  y: number;
  /** Degrees, to keep Inspector fields human-friendly. */
  rotation: number;
  scaleX: number;
  scaleY: number;
  originX: number;
  originY: number;
  visible: boolean;
  /** Texture key + optional atlas frame. Absent for containers. */
  texture?: string;
  frame?: string;
  /** The group this object joins. Groups come back from the layout by name. */
  group?: string;
  body?: BodyDef;
  /** Animation key played in create(). */
  playOnSpawn?: string;
  /** Set when this object is text rather than a sprite. */
  text?: TextDef;
  /** Audio cues the object plays for itself. */
  sounds?: SoundRefs;
  /**
   * Attached behaviour, in execution order: update() is called in list order.
   */
  scripts?: ScriptRef[];
  /**
   * Values for the `@property` fields of the object's own class.
   *
   * A prefab is backed by a class the project owns — an ordinary Phaser sprite
   * subclass — and a field that class marks `@property` is set from here. This
   * is behaviour without a component: nothing is attached, the class simply has
   * fields and the editor gives them values.
   */
  props?: Record<string, unknown>;
  /** Set when this object is a prefab instance. */
  prefab?: string;
  /** Property path -> value, for the fields this instance overrides. */
  overrides?: Record<string, unknown>;
  /** Free-form per-instance gameplay properties. */
  data: Record<string, unknown>;
}

// ---------------------------------------------------------------------------
// Prefabs
// ---------------------------------------------------------------------------

/**
 * A prefab node is an object template: no scene id, no layer, no scene
 * position. `prefab` and `overrides` survive, because a prefab may contain
 * another prefab's instance — which stays sealed rather than being copied in.
 */
export type PrefabNode = Omit<SceneObject, "id" | "layerId" | "parentId"> & {
  /**
   * Stable local id. Overrides, the exposure list and the propagation plan all
   * address a part by this rather than by name, so renaming a child does not
   * silently orphan what pointed at it.
   */
  lid: string;
  children: PrefabNode[];
};

/**
 * A prefab as it is STORED.
 *
 * A base prefab owns its whole tree in `root`. A variant owns nothing but a
 * `base` and a `diff`: it inherits everything and states only its differences,
 * so fixing the base fixes every variant except where one deliberately
 * disagreed. Read one through `resolvePrefab`, never straight off the field.
 */
/**
 * A prefab backed by a class the PROJECT already wrote, rather than one Mosaic
 * generates.
 *
 * This is what lets an imported scene actually run: the generated scene
 * constructs the user's own `Door`, with its own behaviour, positioned by the
 * editor — instead of a lookalike sprite that does nothing.
 */
export interface PrefabSource {
  /** Project-relative module path, e.g. "Door.js". */
  module: string;
  /** Exported name, or "default". */
  export: string;
  /**
   * Constructor parameter names, in order.
   *
   * Recorded because the signature is not conventional across real projects —
   * `(scene, x, y)`, `(name, scene, x, y)` and `(scene, track, size)` all
   * occur — so the call has to be built to match rather than assumed.
   */
  params: string[];
}

export interface PrefabDef {
  name: string;
  /** Property paths instances are allowed to override, e.g. "data.value". */
  exposed: string[];
  /** Set when this prefab is backed by the project's own class. */
  source?: PrefabSource;
  /** The definition tree. Absent on a variant. */
  root?: PrefabNode;
  /** Variant: the prefab this one inherits from. */
  base?: string;
  /** Variant: property path -> value, for what this variant claims for itself. */
  diff?: Record<string, unknown>;
}

/**
 * A prefab with its inheritance applied — what an instance resolves against
 * and what the canvas draws. Never stored; always derived.
 */
export interface ResolvedPrefab {
  name: string;
  exposed: string[];
  root: PrefabNode;
  /**
   * Carried down the chain: a variant of a bound prefab is still that class,
   * so `Coin_Gold` constructs the project's `Coin` like its base does.
   */
  source?: PrefabSource;
  base?: string;
  /** Base first, this prefab last. A base prefab's chain is just its name. */
  chain: string[];
}

// ---------------------------------------------------------------------------
// Animation
// ---------------------------------------------------------------------------

export interface AnimFrameRef {
  textureKey: string;
  frame: string;
  /** ms; overrides the global fps when a pose needs to hold. */
  duration?: number;
}

export interface AnimDef {
  key: string;
  frames: AnimFrameRef[];
  fps: number;
  /**
   * How many times to play again after the first pass. `-1` is forever, `0`
   * plays once — Phaser's own semantics, so nothing has to be translated.
   *
   * This replaced a `loop` boolean, which could only ever say "forever" or
   * "once": playing a hit-flash three times was not expressible at all.
   */
  repeat: number;
  /**
   * Play the frames forward, then backward.
   *
   * A four-frame swing yoyos into seven frames of motion, so it is the
   * difference between drawing four poses and drawing seven.
   */
  yoyo?: boolean;
  /** Read on load from folders written before `repeat` existed. */
  loop?: boolean;
}

/** Forever, once, or a count — whatever the definition says or used to say. */
export function animRepeat(def: Pick<AnimDef, "repeat" | "loop">): number {
  if (typeof def.repeat === "number") return def.repeat;
  return def.loop ? -1 : 0;
}

// ---------------------------------------------------------------------------
// Scenes + project
// ---------------------------------------------------------------------------

/**
 * The camera, as scene data.
 *
 * A level that scrolls is the normal case, and it used to be unauthorable: the
 * exporter set a background colour and world bounds and nothing else, so
 * following the player meant hand-written code in every scene.
 */
export interface CameraDef {
  /** Name of the object to follow. Empty means a fixed camera. */
  follow: string;
  /** 0..1 per axis. 1 is rigid; lower trails behind the target. */
  lerpX: number;
  lerpY: number;
  zoom: number;
  /** Clamp the camera to the scene's bounds so it never shows past the edge. */
  clampToBounds: boolean;
  /** A box in the middle the target can move inside before the camera follows. */
  deadzoneWidth: number;
  deadzoneHeight: number;
}

export const DEFAULT_CAMERA: CameraDef = {
  follow: "",
  lerpX: 1,
  lerpY: 1,
  zoom: 1,
  clampToBounds: true,
  deadzoneWidth: 0,
  deadzoneHeight: 0,
};

/**
 * Which sides of the world rectangle stop a body.
 *
 * Arcade's bounds are one rectangle with a flag per side, and Mosaic used to
 * author only the rectangle — so a game that needs an open edge could not say
 * so. A breakout ball has to be able to fall past the floor; without that the
 * game runs, looks right, and cannot be lost.
 *
 * Absent means all four, which is Arcade's own default and what every scene
 * written before this was built against.
 */
export interface WorldBounds {
  left: boolean;
  right: boolean;
  top: boolean;
  bottom: boolean;
}

export const DEFAULT_WORLD_BOUNDS: WorldBounds = { left: true, right: true, top: true, bottom: true };

/** True when every side stops a body, i.e. nothing needs emitting. */
export function boundsAreClosed(bounds?: WorldBounds): boolean {
  if (!bounds) return true;
  return bounds.left && bounds.right && bounds.top && bounds.bottom;
}

export interface SceneSettings {
  width: number;
  height: number;
  backgroundColor: string;
  gravityY: number;
  gridSize: number;
  /** Absent on scenes written before the camera was authorable. */
  camera?: CameraDef;
  /** Absent on scenes written before the edges were authorable: all four. */
  bounds?: WorldBounds;
  /** Looping background music for the scene. */
  music?: { key: string; volume: number; loop: boolean };
}

export interface SceneData {
  /** Stable key, also the Phaser scene key and the file name. */
  key: string;
  name: string;
  settings: SceneSettings;
  /** Index 0 renders first (bottom). Layer order === Phaser depth on export. */
  layers: Layer[];
  objects: SceneObject[];
}

/**
 * Project-wide defaults every new scene inherits, written to
 * mosaic.config.json and mirrored into the Phaser game config on export. These
 * are project config, not per-scene settings, so the tenth scene matches the
 * first.
 */
export interface ProjectConfig {
  canvas: { width: number; height: number };
  /** Drives the editor grid and the snap increment. */
  tile: number;
  scale: "FIT" | "ENVELOP" | "NONE";
  physics: "arcade" | "matter" | "none";
  /** Forces nearest-neighbour filtering and integer camera positions. */
  pixelArt: boolean;
  /**
   * The language Mosaic writes layout files in. Absent means "work it out":
   * TypeScript when the folder has a tsconfig, JavaScript when it has a
   * package.json without one.
   */
  language?: "ts" | "js";
  /**
   * Where this project keeps things.
   *
   * Mosaic's own layout is the default, but it is a convention rather than a
   * requirement, and a project that predates Mosaic will not follow it — the
   * Phaser examples keep every scene class loose at the folder root. Hardcoding
   * the layout meant those projects indexed zero source files, which in turn
   * meant nothing could be bound to the classes they define.
   */
  paths: ProjectPaths;
}

export interface ProjectPaths {
  /** Source root for the script index. */
  src: string;
  /** Where Mosaic reads and writes `*.scene.json`. */
  scenes: string;
  /** Where Mosaic reads and writes `*.prefab.json`. */
  prefabs: string;
  /** Where art and audio are scanned from. */
  assets: string;
}

export const DEFAULT_PATHS: ProjectPaths = {
  src: "src",
  scenes: "src/scenes",
  prefabs: "src/prefabs",
  assets: "assets",
};

export const DEFAULT_CONFIG: ProjectConfig = {
  paths: DEFAULT_PATHS,
  canvas: { width: 960, height: 540 },
  tile: 32,
  scale: "FIT",
  physics: "arcade",
  pixelArt: true,
};

export interface ProjectData {
  name: string;
  config: ProjectConfig;
  scenes: SceneData[];
  prefabs: PrefabDef[];
  assets: AssetDef[];
  anims: AnimDef[];
  /**
   * Names an object can be tagged with. The layout hands each back as an
   * arcade group, and what collides with what is written in the game's own
   * code — `this.physics.add.collider(player, groups.solid)`.
   */
  groups: string[];
}

/** One entry of the generated Phaser loader manifest. */
export interface LoaderEntry {
  key: string;
  type: "image" | "spritesheet" | "atlas" | "audio" | "tilemap";
  url: string;
  frameConfig?: { frameWidth: number; frameHeight: number; margin: number; spacing: number };
  frames?: AssetFrame[];
}
