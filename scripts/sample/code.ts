export const MAIN = `import Phaser from "phaser";
import { Level_01 } from "./scenes/Level_01";

const scenes = [Level_01];

// Mosaic's RUN opens the game at ?scene=<ClassName>, so it starts on the scene
// you are editing rather than wherever the game normally boots.
const first = new URLSearchParams(window.location.search).get("scene");
scenes.sort((a, b) => Number(b.name === first) - Number(a.name === first));

new Phaser.Game({
  type: Phaser.AUTO,
  width: 960,
  height: 544,
  backgroundColor: "#14171a",
  pixelArt: true,
  roundPixels: true,
  scale: { mode: Phaser.Scale.FIT, autoCenter: Phaser.Scale.CENTER_BOTH },
  physics: { default: "arcade", arcade: { gravity: { x: 0, y: 0 }, debug: false } },
  scene: scenes,
});
`;

export const LEVEL = `import Phaser from "phaser";
import { Coin } from "../prefabs/Coin";
import { Coin_Big } from "../prefabs/Coin_Big";
import { createLevel_01, preloadLevel_01, type Level_01Layout } from "./Level_01.layout";

/**
 * Level 01 — this file is yours.
 *
 * The layout (./Level_01.layout.ts, regenerated by Mosaic on every save) builds
 * the map, the player, the coins, the spikes, the platforms and the goal where
 * the editor placed them. Everything that makes it a game is here: what
 * collides with what, what a coin is worth, what a spike costs, how it ends.
 */
export class Level_01 extends Phaser.Scene {
  layout!: Level_01Layout;
  private score = 0;
  private lives = 0;
  private over = false;
  private start = { x: 0, y: 0 };

  constructor() {
    super("Level_01");
  }

  preload(): void {
    preloadLevel_01(this);
  }

  create(): void {
    this.score = 0;
    this.over = false;
    this.layout = createLevel_01(this);
    const { player, ground, groups, goal, banner } = this.layout;

    // Lives is an @editable field on Player, so the placed Player's value
    // (set in the inspector) is what the round starts with.
    this.lives = player.lives;
    this.start = { x: player.x, y: player.y };
    banner.setVisible(false);

    // What collides with what.
    this.physics.add.collider(player, ground);
    this.physics.add.collider(player, groups.platform);
    this.physics.add.overlap(player, groups.pickup, (_player, coin) => this.take(coin as Coin));
    this.physics.add.overlap(player, groups.hazard, () => this.hurt());
    this.physics.add.overlap(player, goal, () => this.finish("YOU WIN"));

    this.refreshHud();
  }

  update(): void {
    // The bottom edge is open (Scene → World edges), so a fall leaves the world.
    const { player } = this.layout;
    if (!this.over && player.y > this.physics.world.bounds.bottom + 64) this.hurt();
  }

  private take(coin: Coin): void {
    if (!coin.active || this.over) return;
    const { x, y } = coin;
    const burst = coin instanceof Coin_Big;
    this.score += coin.collect();
    if (burst) {
      // A big coin bursts into three small ones, made in code the way you
      // would make any sprite. The pickup group's config keeps them floating.
      for (const dx of [-40, 0, 40]) {
        const bonus = new Coin(this, x + dx, y - 56);
        this.layout.groups.pickup.add(bonus);
        bonus.setDepth(this.layout.player.depth);
      }
    }
    this.refreshHud();
  }

  private hurt(): void {
    if (this.over) return;
    this.lives -= 1;
    this.cameras.main.shake(120, 0.006);
    if (this.lives <= 0) {
      this.finish("GAME OVER");
      return;
    }
    this.layout.player.respawn(this.start.x, this.start.y);
    this.refreshHud();
  }

  private finish(message: string): void {
    if (this.over) return;
    this.over = true;
    this.physics.pause();
    this.layout.banner.setText(message + "\\nclick to play again").setVisible(true);
    this.input.once("pointerdown", () => this.scene.restart());
    this.refreshHud();
  }

  private refreshHud(): void {
    const left = this.layout.groups.pickup.countActive();
    this.layout.hud.setText(
      "SCORE " + this.score + "    COINS LEFT " + left + "    LIVES " + Math.max(0, this.lives),
    );
  }
}
`;

export const PLAYER = `import Phaser from "phaser";
import { PlayerBase } from "./Player.layout";

/**
 * Player — this file is yours.
 *
 * Arrow keys to run, up or space to jump. The art and the body come from
 * PlayerBase, which Mosaic regenerates. The fields tagged @editable show in
 * Mosaic's inspector; the values here are the defaults.
 */
export class Player extends PlayerBase {
  /** Pixels per second. @editable { min: 0, max: 600 } */
  speed = 200;

  /** Upward speed of a jump. @editable { label: "jump velocity", min: -1200, max: 0 } */
  jumpVelocity = -460;

  /** Hits before the round is lost. @editable { min: 1, max: 9 } */
  lives = 3;

  private cursors: Phaser.Types.Input.Keyboard.CursorKeys;

  constructor(scene: Phaser.Scene, x: number, y: number) {
    super(scene, x, y);
    this.cursors = scene.input.keyboard!.createCursorKeys();
  }

  override preUpdate(time: number, delta: number): void {
    super.preUpdate(time, delta);
    const { left, right, up, space } = this.cursors;
    this.setVelocityX(left.isDown ? -this.speed : right.isDown ? this.speed : 0);
    if (left.isDown !== right.isDown) this.setFlipX(left.isDown);
    // blocked: the map and the world edge. touching: a moving platform.
    const grounded = this.body.blocked.down || this.body.touching.down;
    if ((up.isDown || space.isDown) && grounded) this.setVelocityY(this.jumpVelocity);
  }

  /** Back to a point, standing still, with a brief flash. */
  respawn(x: number, y: number): void {
    this.setPosition(x, y);
    this.setVelocity(0, 0);
    this.setAlpha(0.4);
    this.scene.time.delayedCall(400, () => this.setAlpha(1));
  }
}
`;

export const COIN = `import Phaser from "phaser";
import { CoinBase } from "./Coin.layout";

/**
 * Coin — this file is yours.
 *
 * Coin_Big is a variant of this prefab, so it is this class too, bigger and
 * worth more: its numbers are set on the variant in the editor and arrive
 * through its generated class.
 */
export class Coin extends CoinBase {
  /** Added to the score when taken. @editable { min: 1, max: 500 } */
  points = 10;

  constructor(scene: Phaser.Scene, x: number, y: number) {
    super(scene, x, y);
    // A gentle bob, so coins read as something to collect.
    scene.tweens.add({ targets: this, y: y - 6, duration: 700, yoyo: true, repeat: -1, ease: "Sine.inOut" });
  }

  /** Removes it, and says what it was worth. */
  collect(): number {
    this.destroy();
    return this.points;
  }
}
`;

export const MOVING_PLATFORM = `import Phaser from "phaser";
import { MovingPlatformBase } from "./MovingPlatform.layout";

/**
 * MovingPlatform — this file is yours.
 *
 * Slides back and forth around where it was placed. Each one placed in the
 * level has its own range and speed, set in the inspector.
 */
export class MovingPlatform extends MovingPlatformBase {
  /** How far it travels each way, in pixels. @editable { min: 0, max: 600 } */
  range = 96;

  /** Pixels per second. @editable { min: 10, max: 400 } */
  speed = 60;

  private readonly startX: number;

  constructor(scene: Phaser.Scene, x: number, y: number) {
    super(scene, x, y);
    this.startX = x;
  }

  override preUpdate(time: number, delta: number): void {
    super.preUpdate(time, delta);
    if (this.x >= this.startX + this.range) this.setVelocityX(-this.speed);
    else if (this.x <= this.startX - this.range) this.setVelocityX(this.speed);
    else if (this.body.velocity.x === 0) this.setVelocityX(this.speed);
  }
}
`;
