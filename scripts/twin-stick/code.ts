export const MAIN = `import Phaser from "phaser";
import { Level_01 } from "./scenes/Level_01";

const scenes = [Level_01];

// Mosaic's RUN opens the game at ?scene=<ClassName>, so it starts on the scene
// you are editing rather than wherever the game normally boots.
const first = new URLSearchParams(window.location.search).get("scene");
scenes.sort((a, b) => Number(b.name === first) - Number(a.name === first));

const config: Phaser.Types.Core.GameConfig = {
  type: Phaser.AUTO,
  width: 960,
  height: 540,
  backgroundColor: "#14171a",
  pixelArt: true,
  roundPixels: true,
  scale: { mode: Phaser.Scale.FIT, autoCenter: Phaser.Scale.CENTER_BOTH },
  physics: { default: "arcade", arcade: { gravity: { x: 0, y: 0 }, debug: false } },
  // The second stick. Without this the gamepad plugin is not created at all.
  input: { gamepad: true },
  scene: scenes,
};

new Phaser.Game(config);
`;

export const LEVEL = `import Phaser from "phaser";
import { Bullet } from "../prefabs/Bullet";
import { Enemy } from "../prefabs/Enemy";
import { Enemy_Fast } from "../prefabs/Enemy_Fast";
import { FIRE } from "../prefabs/Player";
import { SPAWN, type SpawnKind } from "../prefabs/Spawner";
import { createLevel_01, preloadLevel_01, type Level_01Layout } from "./Level_01.layout";

/** Enough to be a fight, few enough that the arena never fills up. */
const MAX_ENEMIES = 24;

/**
 * Level 01 — this file is yours.
 *
 * The layout (./Level_01.layout.ts, regenerated by Mosaic on every save) puts
 * the arena, the player, the first enemies and the spawners where the editor
 * placed them. Everything that makes it a game is below: who shoots, what a
 * bullet hits, what happens when the player is touched.
 */
export class Level_01 extends Phaser.Scene {
  layout!: Level_01Layout;
  private score = 0;
  private over = false;

  constructor() {
    super("Level_01");
  }

  preload(): void {
    preloadLevel_01(this);
  }

  create(): void {
    this.score = 0;
    this.over = false;
    this.layout = createLevel_01(this);
    const { player, walls, groups, banner } = this.layout;
    // No bullet is placed in the editor, but the group is still handed back.
    // Adding to a layout group restores the authored body and layer depth.
    const { enemy: enemies, bullet: bullets } = groups;
    banner.setVisible(false);

    for (const enemy of enemies.getChildren()) (enemy as Enemy).target = player;

    // The player decides WHEN to fire; the scene owns what a shot is.
    player.on(FIRE, (x: number, y: number, angle: number) => {
      const bullet = Bullet.spawn(this, x, y);
      bullets.add(bullet);
      bullet.fire(angle);
    });

    // A spawner only says "one here, of this kind". Spawn is the prefab's own
    // helper: new, plus the values set on the definition in the editor.
    const onSpawn = (x: number, y: number, kind: SpawnKind) => {
      if (this.over || enemies.countActive() >= MAX_ENEMIES) return;
      const enemy = kind === "Enemy_Fast" ? Enemy_Fast.spawn(this, x, y) : Enemy.spawn(this, x, y);
      enemies.add(enemy);
      enemy.target = player;
    };
    this.events.on(SPAWN, onSpawn);
    this.events.once(Phaser.Scenes.Events.SHUTDOWN, () => this.events.off(SPAWN, onSpawn));

    // What collides with what.
    this.physics.add.collider(player, walls);
    this.physics.add.collider(enemies, walls);
    this.physics.add.collider(enemies, enemies);
    this.physics.add.collider(bullets, walls, (bullet) => {
      (bullet as unknown as Bullet).destroy();
    });
    this.physics.add.overlap(bullets, enemies, (bullet, hit) => {
      const enemy = hit as unknown as Enemy;
      (bullet as unknown as Bullet).destroy();
      if (enemy.hit()) this.addScore(enemy.points);
    });
    this.physics.add.overlap(player, enemies, (_player, hit) => {
      (hit as unknown as Enemy).destroy();
      if (player.hurt()) this.gameOver();
      this.refreshHud();
    });

    this.refreshHud();
  }

  private addScore(points: number): void {
    this.score += points;
    this.refreshHud();
  }

  private refreshHud(): void {
    const { hud, player } = this.layout;
    hud.setText(\`SCORE \${this.score}    HP \${Math.max(0, player.hp)}\`);
  }

  private gameOver(): void {
    this.over = true;
    this.physics.pause();
    this.layout.banner.setVisible(true);
    this.input.once("pointerdown", () => this.scene.restart());
  }
}
`;

export const PLAYER = `import Phaser from "phaser";
import { property } from "../scripts/ScriptComponent";
import { PlayerBase } from "./Player.layout";

/** Emitted on the player when a shot leaves: (x, y, angle in radians). */
export const FIRE = "fire";

const STICK_DEADZONE = 0.25;

/**
 * Player — this file is yours.
 *
 * Twin-stick: one hand moves, the other aims. On a keyboard that is WASD and
 * the mouse; on a gamepad it is the two sticks, and pushing the right stick
 * fires. The art and the body come from PlayerBase, which Mosaic regenerates.
 *
 * The fields marked @property are the ones worth tuning without a rebuild:
 * they show in Mosaic's inspector, and the value set there wins.
 */
export class Player extends PlayerBase {
  @property({ min: 0, max: 600 })
  speed = 240;

  @property({ label: "shots per second", min: 1, max: 20 })
  fireRate = 6;

  @property({ min: 1, max: 10 })
  hp = 3;

  private keys: Record<"W" | "A" | "S" | "D", Phaser.Input.Keyboard.Key>;
  private nextShot = 0;
  private move = new Phaser.Math.Vector2();

  constructor(scene: Phaser.Scene, x: number, y: number) {
    super(scene, x, y);
    this.keys = scene.input.keyboard!.addKeys("W,A,S,D") as typeof this.keys;
  }

  override preUpdate(time: number, delta: number): void {
    super.preUpdate(time, delta);
    const pad = this.scene.input.gamepad?.getPad(0);

    // --- left hand: move
    this.move.set(
      Number(this.keys.D.isDown) - Number(this.keys.A.isDown),
      Number(this.keys.S.isDown) - Number(this.keys.W.isDown),
    );
    if (pad && pad.leftStick.length() > STICK_DEADZONE) this.move.copy(pad.leftStick);
    if (this.move.lengthSq() > 1) this.move.normalize();
    this.setVelocity(this.move.x * this.speed, this.move.y * this.speed);

    // --- right hand: aim, and fire
    let angle: number;
    let firing: boolean;
    if (pad && pad.rightStick.length() > STICK_DEADZONE) {
      angle = pad.rightStick.angle();
      firing = true;
    } else {
      const pointer = this.scene.input.activePointer;
      // Asked of the camera each frame: the pointer's own world position goes
      // stale the moment the camera scrolls under a mouse that is not moving.
      const at = this.scene.cameras.main.getWorldPoint(pointer.x, pointer.y);
      angle = Phaser.Math.Angle.Between(this.x, this.y, at.x, at.y);
      firing = pointer.isDown;
    }
    // The capsule is drawn pointing up; rotation 0 points right.
    this.setRotation(angle + Math.PI / 2);

    if (firing && time >= this.nextShot) {
      this.nextShot = time + 1000 / this.fireRate;
      this.emit(FIRE, this.x + Math.cos(angle) * 22, this.y + Math.sin(angle) * 22, angle);
    }
  }

  /** Takes one hit. True when it was the last one. */
  hurt(): boolean {
    this.hp -= 1;
    this.setAlpha(0.4);
    this.scene.time.delayedCall(120, () => this.setAlpha(1));
    return this.hp <= 0;
  }
}
`;

export const ENEMY = `import Phaser from "phaser";
import { property } from "../scripts/ScriptComponent";
import { EnemyBase } from "./Enemy.layout";

/**
 * Enemy — this file is yours.
 *
 * Walks at whatever it has been told to chase. Enemy_Fast is a variant of this
 * prefab, so it IS this class — same behaviour — with different numbers set on
 * its definition in the editor.
 */
export class Enemy extends EnemyBase {
  @property({ min: 0, max: 400 })
  speed = 90;

  @property({ min: 1, max: 20 })
  hp = 2;

  @property({ label: "points when destroyed", min: 0, max: 1000 })
  points = 10;

  /** Set by the scene: the layout does not know who is hunting whom. */
  target?: Phaser.GameObjects.Sprite;

  override preUpdate(time: number, delta: number): void {
    super.preUpdate(time, delta);
    if (!this.target?.active) {
      this.setVelocity(0, 0);
      return;
    }
    const angle = this.scene.physics.moveToObject(this, this.target, this.speed);
    this.setRotation(angle + Math.PI / 2);
  }

  /** Takes one bullet. True when that destroyed it. */
  hit(): boolean {
    this.hp -= 1;
    if (this.hp <= 0) {
      this.destroy();
      return true;
    }
    this.setAlpha(0.5);
    this.scene.time.delayedCall(60, () => this.active && this.setAlpha(1));
    return false;
  }
}
`;

export const BULLET = `import { property } from "../scripts/ScriptComponent";
import { BulletBase } from "./Bullet.layout";

/**
 * Bullet — this file is yours.
 *
 * Never placed in the editor: it is a prefab so that its art, its body and its
 * numbers are authored there, and it is made from code with Bullet.spawn().
 */
export class Bullet extends BulletBase {
  @property({ min: 50, max: 1500 })
  speed = 520;

  @property({ label: "lifetime (ms)", min: 50, max: 5000 })
  lifetime = 900;

  private diesAt = Infinity;

  /**
   * Sends it on its way. Call after it has joined its group: joining resets
   * the body, velocity included, and the layout's group puts back only the
   * authored shape and settings.
   */
  fire(angle: number): this {
    this.setRotation(angle);
    this.scene.physics.velocityFromRotation(angle, this.speed, this.body.velocity);
    this.diesAt = this.scene.time.now + this.lifetime;
    return this;
  }

  override preUpdate(time: number, delta: number): void {
    super.preUpdate(time, delta);
    if (time >= this.diesAt) this.destroy();
  }
}
`;

export const SPAWNER = `import Phaser from "phaser";
import { property } from "../scripts/ScriptComponent";
import { SpawnerBase } from "./Spawner.layout";

/** Emitted on the scene when a spawner wants an enemy: (x, y, kind). */
export const SPAWN = "spawn-enemy";

export type SpawnKind = "Enemy" | "Enemy_Fast";

/**
 * Spawner — this file is yours.
 *
 * A marker you place in the editor. It draws there so you can see and move it,
 * hides itself in the game, and asks the scene for an enemy on a timer. Each
 * one placed has its own interval and kind, set in the inspector — which is
 * the whole difficulty curve of the arena, with no code involved.
 */
export class Spawner extends SpawnerBase {
  @property({ label: "seconds between spawns", min: 0.5, max: 60, step: 0.5 })
  interval = 4;

  @property({ label: "first spawn after (s)", min: 0, max: 60, step: 0.5 })
  delay = 2;

  @property({ options: ["Enemy", "Enemy_Fast"] })
  kind: SpawnKind = "Enemy";

  private next = -1;

  constructor(scene: Phaser.Scene, x: number, y: number) {
    super(scene, x, y);
    this.setVisible(false);
  }

  override preUpdate(time: number, delta: number): void {
    super.preUpdate(time, delta);
    // The values arrive after the constructor, so the clock starts here.
    if (this.next < 0) this.next = time + this.delay * 1000;
    if (time < this.next) return;
    this.next = time + this.interval * 1000;
    this.scene.events.emit(SPAWN, this.x, this.y, this.kind);
  }
}
`;
