import Phaser from "phaser";
import { Bullet } from "../prefabs/Bullet";
import { Explosion } from "../prefabs/Explosion";
import { Robot } from "../prefabs/Robot";
import { Zombie } from "../prefabs/Zombie";
import type { Barrel } from "../prefabs/Barrel";
import type { Pickup } from "../prefabs/Pickup";
import type { Spawner } from "../prefabs/Spawner";
import { createLevel_01, preloadLevel_01, type Level_01Layout } from "./Level_01.layout";

/** Damage a barrel does to the player standing in its blast. */
const BLAST_TO_PLAYER = 35;
/** Health given back for clearing a wave. */
const WAVE_HEAL = 25;

/**
 * Level 01 — this file is yours.
 *
 * The layout (./Level_01.layout.ts, regenerated by Mosaic on every save) builds
 * the Tiled map, the compound, the barrels, the spawners and everyone in it,
 * where the editor placed them. Everything that makes it a game is here: what
 * collides with what, what a bullet does to a zombie, how a barrel goes up,
 * and how the waves come.
 */
export class Level_01 extends Phaser.Scene {
  layout!: Level_01Layout;
  private wave = 0;
  /** Enemies the current wave has still to let out. */
  private quota = 0;
  private score = 0;
  private over = false;
  private spawners: Spawner[] = [];

  constructor() {
    super("Level_01");
  }

  preload(): void {
    preloadLevel_01(this);
  }

  create(): void {
    this.wave = 0;
    this.quota = 0;
    this.score = 0;
    this.over = false;
    this.layout = createLevel_01(this);
    const { player, walls, groups, banner } = this.layout;
    const { spawnerNorth, spawnerSouth, spawnerWest, spawnerEast } = this.layout;
    this.spawners = [spawnerNorth, spawnerSouth, spawnerWest, spawnerEast];
    banner.setVisible(false);

    // The player shoots into the bullet group, and starts with the gun the
    // placed Player was given in the inspector.
    player.bullets = groups.bullet;
    player.arm(player.weapon);

    // What collides with what.
    const solid = [walls, groups.cover, groups.barrel];
    this.physics.add.collider(player, solid);
    this.physics.add.collider(groups.enemy, solid);
    this.physics.add.collider(groups.enemy, groups.enemy);
    this.physics.add.collider(groups.bullet, [walls, groups.cover], (bullet) => (bullet as Bullet).spark());
    this.physics.add.overlap(groups.bullet, groups.enemy, (bullet, enemy) =>
      this.shoot(bullet as Bullet, enemy as Zombie),
    );
    this.physics.add.overlap(groups.bullet, groups.barrel, (bullet, barrel) => {
      (bullet as Bullet).spark();
      if ((barrel as Barrel).hit()) this.blowUp(barrel as Barrel);
    });
    this.physics.add.overlap(player, groups.enemy, (_player, enemy) => this.bitten(enemy as Zombie));
    this.physics.add.overlap(player, groups.pickup, (_player, item) => this.collect(item as Pickup));

    this.input.keyboard?.on("keydown-R", () => player.reload());
    this.nextWave();
  }

  update(time: number): void {
    if (this.over) return;
    this.refreshHud();
    const { groups } = this.layout;

    for (const spawner of this.spawners) {
      if (this.quota <= 0) break;
      // Robots join from the second wave.
      if (spawner.kind === "Robot" && this.wave < 2) continue;
      if (!spawner.ready(time)) continue;
      const enemy = spawner.kind === "Robot" ? new Robot(this, spawner.x, spawner.y) : new Zombie(this, spawner.x, spawner.y);
      groups.enemy.add(enemy);
      enemy.setDepth(this.layout.player.depth);
      spawner.pulse();
      this.quota -= 1;
    }

    if (this.quota <= 0 && groups.enemy.countActive() === 0) {
      this.layout.player.heal(WAVE_HEAL);
      this.nextWave();
    }
  }

  private nextWave(): void {
    this.wave += 1;
    this.quota = 4 + this.wave * 4;
    // Each spawner starts its own clock again, from its own delay.
    for (const spawner of this.spawners) spawner.rewind();
    this.announce("WAVE " + this.wave, 1600);
  }

  private shoot(bullet: Bullet, enemy: Zombie): void {
    if (!bullet.active || !enemy.alive) return;
    bullet.spark();
    if (enemy.hurt(bullet.damage)) this.score += enemy.points;
  }

  private bitten(enemy: Zombie): void {
    if (this.over || !enemy.alive || !enemy.canBite(this.time.now)) return;
    this.hurtPlayer(enemy.damage);
  }

  private hurtPlayer(amount: number): void {
    const { player } = this.layout;
    if (player.hurt(amount)) {
      this.finish("YOU DIDN'T HOLD OUT\nwave " + this.wave + " · score " + this.score + "\n\nclick to try again");
    }
  }

  private collect(item: Pickup): void {
    if (!item.active) return;
    this.layout.player.arm(item.weapon);
    this.sound.play("audio_pickup");
    this.announce(item.weapon.toUpperCase(), 900);
    item.destroy();
  }

  /** A barrel goes up: everything near it is hurt, and nearby barrels follow. */
  private blowUp(barrel: Barrel): void {
    if (!barrel.active) return;
    const { x, y } = barrel;
    const { radius, damage } = barrel;
    barrel.destroy();
    // The explosion's animation and sound are set on its prefab in the
    // editor, and play from its constructor: new is all it takes.
    const blast = new Explosion(this, x, y);
    blast.setDepth(this.layout.player.depth + 1);
    // A scorch mark from the same sheet as the tiles, between the ground and the walls.
    this.add.image(x, y, "tiles", 20).setDepth(this.layout.details.depth + 0.5).setAlpha(0.8);
    this.cameras.main.shake(220, 0.01);

    const near = (o: Phaser.GameObjects.Components.Transform) =>
      Phaser.Math.Distance.Between(x, y, o.x, o.y) <= radius;
    for (const enemy of this.layout.groups.enemy.getChildren() as Zombie[]) {
      if (enemy.alive && near(enemy) && enemy.hurt(damage)) this.score += enemy.points;
    }
    for (const other of this.layout.groups.barrel.getChildren() as Barrel[]) {
      if (other.active && near(other)) this.time.delayedCall(140, () => this.blowUp(other));
    }
    if (near(this.layout.player)) this.hurtPlayer(BLAST_TO_PLAYER);
  }

  private announce(message: string, ms: number): void {
    const { banner } = this.layout;
    banner.setText(message).setVisible(true).setAlpha(1);
    this.tweens.killTweensOf(banner);
    this.tweens.add({ targets: banner, alpha: 0, delay: ms, duration: 400 });
  }

  private finish(message: string): void {
    if (this.over) return;
    this.over = true;
    this.refreshHud();
    this.physics.pause();
    const { banner } = this.layout;
    this.tweens.killTweensOf(banner);
    banner.setText(message).setVisible(true).setAlpha(1);
    this.time.delayedCall(600, () => this.input.once("pointerdown", () => this.scene.restart()));
  }

  private refreshHud(): void {
    const { player, status, score } = this.layout;
    const gun = player.reloading ? "reloading…" : player.ammo + "/" + player.clip;
    status.setText("HP " + Math.max(0, player.health) + "    " + player.weapon.toUpperCase() + " " + gun);
    score.setText("WAVE " + this.wave + "    SCORE " + this.score);
  }
}
